            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="true" aria-controls="care-panel-1" id="care-btn-1">
                <span class="acc-num">01</span>
                <span class="acc-title">Choose the right grass type</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-1" role="region" aria-labelledby="care-btn-1">
              <div class="acc-inner">
                <p>Delhi is a warm-season city. Bermuda and Zoysia handle the heat far better than cool-season varieties, and they recover quickly from foot traffic. Match your choice to the light your patch actually gets — not the light you wish it got.</p>
                <p class="tip"><svg class="icon" aria-hidden="true"><use href="#i-spark"/></svg><span><strong>Nursery note:</strong> a lawn with less than four hours of direct sun will always struggle. That is a shade problem, not a fertiliser problem.</span></p>
