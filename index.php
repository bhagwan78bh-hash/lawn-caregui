          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-2" id="care-btn-2">
                <span class="acc-num">02</span>
                <span class="acc-title">Water deeply, not daily</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-2" role="region" aria-labelledby="care-btn-2">
              <div class="acc-inner">
                <p>Shallow daily sprinkling keeps roots near the surface. Water two or three times a week, long enough to soak 10–15 cm down, and the roots will follow. Early morning is best: the grass dries before evening and fungal problems have less to work with.</p>
                <p class="tip"><svg class="icon" aria-hidden="true"><use href="#i-spark"/></svg><span><strong>Quick test:</strong> push a screwdriver into the soil. If it slides in easily, you have watered enough.</span></p>
              </div>
            </div>
          </article>

          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-3" id="care-btn-3">
                <span class="acc-num">03</span>
                <span class="acc-title">Mow high, mow sharp</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-3" role="region" aria-labelledby="care-btn-3">
              <div class="acc-inner">
                <p>Keep the lawn at roughly 6–10 cm (2.5–4 inches) and never remove more than a third of the blade in one cut. Scalping stresses the grass and invites weeds. A sharp blade makes a clean cut; a dull one tears the tips and leaves them brown.</p>
                <p class="tip"><svg class="icon" aria-hidden="true"><use href="#i-spark"/></svg><span><strong>Nursery note:</strong> change your mowing direction each time to stop ruts and leaning grass.</span></p>
              </div>
            </div>
          </article>

          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-4" id="care-btn-4">
                <span class="acc-num">04</span>
                <span class="acc-title">Aerate once a year</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-4" role="region" aria-labelledby="care-btn-4">
              <div class="acc-inner">
                <p>Delhi's clay-heavy soils compact easily, especially along walkways and anywhere children play. Aerating pulls small cores or punches holes so air, water and nutrients can reach the roots again. Do it in the growing season, then water lightly.</p>
              </div>
            </div>
          </article>

          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-5" id="care-btn-5">
                <span class="acc-num">05</span>
                <span class="acc-title">Feed by the season</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-5" role="region" aria-labelledby="care-btn-5">
              <div class="acc-inner">
                <p>Warm-season grasses do their growing in late spring and summer. Feed then with a slow-release lawn fertiliser, and go easy during the hottest weeks — food that is not used runs off or burns the blades. A soil test beats guesswork.</p>
              </div>
            </div>
          </article>

          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-6" id="care-btn-6">
                <span class="acc-num">06</span>
                <span class="acc-title">Crowd out weeds</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-6" role="region" aria-labelledby="care-btn-6">
              <div class="acc-inner">
                <p>The best weed control is a dense lawn. Seed bare patches, keep the mowing height up and feed on schedule, and weeds have nowhere to land. If you already have an invasion, identify it first: hand-pull a few, and use a labelled herbicide for the rest.</p>
              </div>
            </div>
          </article>

          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-7" id="care-btn-7">
                <span class="acc-num">07</span>
                <span class="acc-title">Fix drainage before anything else</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-7" role="region" aria-labelledby="care-btn-7">
              <div class="acc-inner">
                <p>If water sits on the surface after rain, roots are drowning and disease follows. Aerate, work in organic matter, or channel water away with a drain. In Delhi's monsoon, a lawn that drains well survives; a lawn that pools does not.</p>
                <p class="tip"><svg class="icon" aria-hidden="true"><use href="#i-spark"/></svg><span><strong>Nursery note:</strong> a slight slope away from the wall is worth more than any rescue treatment later.</span></p>
              </div>
            </div>
          </article>

          <article class="acc-item">
            <h3 class="acc-heading">
              <button class="acc-trigger" type="button" aria-expanded="false" aria-controls="care-panel-8" id="care-btn-8">
                <span class="acc-num">08</span>
                <span class="acc-title">Watch for pests — don't spray blind</span>
                <span class="acc-icon" aria-hidden="true"></span>
              </button>
            </h3>
            <div class="acc-panel" id="care-panel-8" role="region" aria-labelledby="care-btn-8">
              <div class="acc-inner">
                <p>Grubs, ants and chinch bugs are the usual suspects. Brown patches, spongy turf or a lawn that lifts like a carpet are clues. Identify the pest before treating: organic options and beneficial insects handle mild cases, and a professional is worth it for a severe infestation.</p>
              </div>
            </div>
